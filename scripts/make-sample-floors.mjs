#!/usr/bin/env node
// Usage: npm run floors:sample -- <organisation> <building id> [options]
//          --floors 6        number of floors (default: the building height / 3.4 m)
//          --theme office    office | factory | warehouse | lab (room names)
//          --folder name     building folder name (default: from the building name)
//          --force           replace an existing folder that was NOT generated here
//
// Writes template floor plans for one building into
// public/data/<organisation>/<folder>/L01 ... (level, corridor, shops, walls, pois),
// laid out inside the building's footprint (scripts/lib/sample-floors.mjs). They
// are a start for drawing the real floors in QGIS: the rooms are invented and the
// map labels them as a sample until "sample" is removed from building.json.
// A folder made by this script is replaced freely; any other folder is kept
// unless --force is given.
import { existsSync } from "node:fs";
import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { buildOrgIndex, DATA_DIR, listOrganisations } from "./lib/catalog.mjs";
import { SAMPLE_THEMES, sampleFloors } from "./lib/sample-floors.mjs";
import { folderKey } from "../src/indoor/levels.js";

const root = fileURLToPath(new URL("..", import.meta.url));
const METRES_PER_FLOOR = 3.4;

function parseArguments(argv) {
  const options = { positional: [] };
  for (let i = 0; i < argv.length; i += 1) {
    const value = argv[i];
    if (value === "--force") options.force = true;
    else if (value.startsWith("--")) options[value.slice(2)] = argv[++i];
    else options.positional.push(value);
  }
  return options;
}

const text = (data) => `${JSON.stringify(data, null, 1)}\n`;
// One feature per line, like the files QGIS writes.
const geojson = ({ features, ...head }) => `{\n${Object.entries(head).map(([key, value]) => `${JSON.stringify(key)}: ${JSON.stringify(value)}`).join(",\n")},\n"features": [\n${features.map((feature) => JSON.stringify(feature)).join(",\n")}\n]\n}\n`;

export async function writeSampleFloors({ org, id, floors, theme = "office", folder, force = false, log = console.log }) {
  if (!listOrganisations(root).includes(org)) throw new Error(`No organisation folder ${DATA_DIR}/${org}/. Known: ${listOrganisations(root).join(", ") || "none"}.`);
  if (!SAMPLE_THEMES[theme]) throw new Error(`Unknown theme "${theme}". Use one of: ${Object.keys(SAMPLE_THEMES).join(", ")}.`);
  const index = buildOrgIndex(root, org);
  if (!index.datasets.buildings) throw new Error(`${org} has no buildings file yet.`);
  const buildings = JSON.parse(await readFile(path.join(root, DATA_DIR, org, index.datasets.buildings), "utf8"));
  const building = buildings.features.find((feature) => String(feature.properties?.id) === String(id));
  if (!building) throw new Error(`No building with id ${id} in ${index.datasets.buildings}.`);
  const p = building.properties;
  const height = Number(p.top_m) - (Number(p.base_m) || 0);
  const count = Number(floors) > 0 ? Math.round(Number(floors)) : Math.max(1, Math.round((Number.isFinite(height) ? height : METRES_PER_FLOOR) / METRES_PER_FLOOR));
  const existing = index.indoor.find((item) => item.building_id === String(p.id));
  const name = folder || existing?.folder || folderKey(p.name_en_short || p.name_en || `building-${p.id}`);
  const target = path.join(root, DATA_DIR, org, name);
  if (existsSync(target)) {
    let generated = false;
    try { generated = JSON.parse(await readFile(path.join(target, "building.json"), "utf8")).sample === true; } catch { /* not generated here */ }
    if (!generated && !force) throw new Error(`${DATA_DIR}/${org}/${name}/ already holds floor plans that were not generated by this script. Nothing was written (use --force to replace them).`);
    await rm(target, { recursive: true });
  }
  const { files, summary } = sampleFloors(building, { floors: count, theme });
  for (const [file, data] of Object.entries(files)) {
    await mkdir(path.dirname(path.join(target, file)), { recursive: true });
    await writeFile(path.join(target, file), file.endsWith(".geojson") ? geojson(data) : text(data), "utf8");
  }
  log(`${org}/${name}: ${summary.floors} floors, ${summary.rooms} rooms, ${summary.size.join(" x ")} m plan, entrance at the ${summary.entrance} (${String(p.name_en || "").trim() || `building ${p.id}`})`);
  return { folder: name, ...summary };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const options = parseArguments(process.argv.slice(2));
  const [org, id] = options.positional;
  if (!org || !id) {
    console.error("Usage: npm run floors:sample -- <organisation> <building id> [--floors N] [--theme office|factory|warehouse|lab] [--folder name] [--force]");
    process.exit(1);
  }
  try { await writeSampleFloors({ org, id, floors: options.floors, theme: options.theme, folder: options.folder, force: options.force }); }
  catch (error) { console.error(error.message); process.exit(1); }
}
